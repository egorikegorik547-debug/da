/**
 * «Наследие технологий»: у каждой из ~200 технологий есть осязаемое продолжение.
 *  building — новая постройка / оборона на карте
 *  order    — новый приказ или инструмент (кнопка в меню «Указы» [I])
 *  craft    — новый рецепт крафта / предмет / юнит
 *  look     — видимая перемена в быту людей и зданий
 *  decree   — указ власти, голосование, совет
 *  class    — уникальное действие или постройка специализации
 */
export type LegKind = 'building' | 'order' | 'craft' | 'look' | 'decree' | 'class';

export const KIND_INFO: Record<LegKind, { name: string; icon: string; color: string }> = {
  building: { name: 'Постройка', icon: '🏗️', color: '#c9a35a' },
  order: { name: 'Приказ', icon: '📜', color: '#7bc043' },
  craft: { name: 'Крафт', icon: '⚒️', color: '#f08a24' },
  look: { name: 'Быт', icon: '👁️', color: '#4aa8ff' },
  decree: { name: 'Указ', icon: '🏛️', color: '#b362ff' },
  class: { name: 'Класс', icon: '⭐', color: '#ffd45a' },
};

export type ResBag = Partial<Record<'wood' | 'stone' | 'food' | 'goods' | 'gold' | 'know', number>>;
export type Op = (string | number)[];

export interface Deed {
  cost: ResBag;
  gain: ResBag;
  cd: number;
  op?: Op;
}

export interface Legacy {
  id: string;
  kind: LegKind;
  title: string;
  desc: string;
  bld?: string[];
  item?: string;
  deed?: Deed;
}

const KEYS = ['wood', 'stone', 'food', 'goods', 'gold', 'know'] as const;
const $ = (s: string): ResBag => {
  const o: ResBag = {};
  if (!s) return o;
  for (const part of s.split(' ')) {
    const m = /^([a-z]+)(\d+)$/.exec(part);
    if (m && (KEYS as readonly string[]).includes(m[1])) o[m[1] as (typeof KEYS)[number]] = +m[2];
  }
  return o;
};

export const LEGACY: Record<string, Legacy> = {};
const put = (l: Legacy) => {
  LEGACY[l.id] = l;
};
/** постройка (новая «tb_*» либо уже существующая) */
const B = (id: string, title: string, desc: string, existing?: string[]) => put({ id, kind: 'building', title, desc, bld: existing ?? (TECH_BUILDS_BY_TECH[id] ?? []).map((t) => t.id) });
/** крафт */
const C = (id: string, title: string, item: string, desc: string) => put({ id, kind: 'craft', title, desc, item });
/** быт */
const L = (id: string, title: string, desc: string) => put({ id, kind: 'look', title, desc });
const mk = (kind: LegKind) => (id: string, title: string, desc: string, cost: string, gain: string, cd: number, ...op: Op) => put({ id, kind, title, desc, deed: { cost: $(cost), gain: $(gain), cd, op: op.length ? op : undefined } });
const O = mk('order');
const D = mk('decree');
const X = mk('class');

